def _is_missing(value: object) -> bool:
    return pd.isna(value)


def _label_text(value: object) -> str:
    text = "" if _is_missing(value) else str(value)
    return " ".join(text.replace("_", " ").replace("-", " ").split())


def _pretty_label(value: object) -> str:
    return latex_escape(_label_text(value))


def _compact_label_text(value: object) -> str:
    text = _label_text(value)
    for term, replacement in COMPACT_LABEL_REPLACEMENTS:
        pattern = rf"\b{re.escape(term)}\b"

        def replace(match: re.Match[str]) -> str:
            if match.group(0)[:1].isupper():
                return replacement[:1].upper() + replacement[1:]
            return replacement

        text = re.sub(pattern, replace, text, flags=re.IGNORECASE)
    return text


def _compact_label(value: object) -> str:
    return latex_escape(_compact_label_text(value))


def _compact_label_words(value: object) -> list[str]:
    return [latex_escape(word) for word in _compact_label_text(value).split()]


def _bold_latex(value: str) -> str:
    return rf"\textbf{{{value}}}" if value else ""


def _behavior_label_lines(value: object) -> list[str]:
    text = _label_text(value).lower()
    if text == "deceive":
        return [_bold_latex("deception")]
    if text == "literal instruction following":
        return [_bold_latex("literalism")]
    if text == "strategic aggression":
        return [_bold_latex("strategic"), _bold_latex("aggression")]
    if text == "non compliance":
        return [_bold_latex("non"), _bold_latex("compliance")]
    return [_bold_latex(_pretty_label(value))]


def _manipulated_component_label(value: object) -> str:
    if _is_missing(value):
        return "--"
    key = str(value).strip().lower()
    return MANIPULATED_COMPONENT_LABELS.get(key, _pretty_label(value))


def _format_decimal(value: object, digits: int = 3) -> str:
    if _is_missing(value):
        return "--"
    return f"{float(value):.{digits}f}"


def _format_int(value: object) -> str:
    if _is_missing(value):
        return "--"
    return str(int(value))


def _format_p(value: object) -> str:
    if _is_missing(value):
        return "--"
    value = float(value)
    if value < 0.001:
        return r"$<.001$"
    return f"{value:.3f}"


def _format_table_bf(value: object) -> str:
    if _is_missing(value):
        return "--"
    value = float(value)
    if value == 0:
        return "0"
    if abs(value) >= 1000:
        exponent = int(math.floor(math.log10(abs(value))))
        mantissa = value / (10**exponent)
        return rf"${mantissa:.1f}e{exponent}$"
    if abs(value) < 0.001:
        return r"$<10^{-3}$"
    return f"{value:.3f}"


def _effect_label(value: object) -> str:
    return EFFECT_LABELS.get(str(value), _pretty_label(value))


def _latex_caption(value: str) -> str:
    parts = re.split(r"(\$[^$]*\$)", value)
    return "".join(part if part.startswith("$") else latex_escape(part) for part in parts)


def _evidence_class_result_rows(frame: pd.DataFrame) -> list[str]:
    lines = []
    previous_behavior = None
    previous_group = None
    behavior_lines: list[str] = []
    behavior_line_index = 0
    cause_words: list[str] = []
    cause_word_index = 0

    for row in frame.itertuples(index=False):
        behavior = row.behavior_name
        group = (row.behavior_name, row.variable)
        is_new_group = group != previous_group
        if behavior != previous_behavior:
            behavior_lines = _behavior_label_lines(behavior)
            behavior_line_index = 0
        if is_new_group:
            cause_words = _compact_label_words(row.variable)
            cause_word_index = 0

        behavior_cell = (
            behavior_lines[behavior_line_index]
            if behavior_line_index < len(behavior_lines)
            else ""
        )
        cause_cell = (
            cause_words[cause_word_index]
            if cause_word_index < len(cause_words)
            else ""
        )
        invariant_cells = [
            _manipulated_component_label(row.manipulated_component),
            _format_int(row.num_domains),
            _format_int(row.num_groups),
            _format_int(row.num_causal_values),
            _format_int(row.num_rounds),
        ]
        if not is_new_group:
            invariant_cells = [""] * len(invariant_cells)

        cells = [
            behavior_cell,
            cause_cell,
            *invariant_cells,
            _compact_label(row.outcome),
            _format_int(row.n),
            _format_table_bf(row.bf10),
            _format_decimal(row.Delta),
            _format_decimal(row.tau),
            _format_p(row.p_tau),
            _effect_label(row.effect_class),
        ]
        lines.append(" & ".join(cells) + r" \\")

        previous_behavior = behavior
        previous_group = group
        behavior_line_index += 1
        cause_word_index += 1
    return lines


