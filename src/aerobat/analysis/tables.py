def _ratio(score: object, baseline: object) -> str:
    if _is_missing(score) or _is_missing(baseline) or float(baseline) == 0:
        return "--"
    return rf"$\times${float(score) / float(baseline):.1f}"


def environment_fidelity_latex(numbers: Mapping[str, object]) -> str:
    """Create the manuscript-format environment fidelity table."""
    task1_all = float(numbers["task1_exact_match_all"])
    task1_causal = float(numbers["task1_exact_match_causal"])
    task1_random_all = float(numbers["task1_random_match_all"])
    task1_random_causal = float(numbers["task1_random_match_causal"])
    task2_item = float(numbers["task2_item_accuracy_pct"]) / 100
    task2_group = float(numbers["task2_group_accuracy_pct"]) / 100
    task2_random_item = float(numbers["task2_random_baseline_pct"]) / 100
    task2_random_group = float(numbers["task2_group_random_baseline_pct"]) / 100
    task3_score = numbers.get("task3_human_eval_score")
    task3_score_text = "--" if _is_missing(task3_score) else rf"\textbf{{{float(task3_score):.3f}}}"
    lines = [
        r"\begin{table*}[!h]",
        r"\centering",
        r"\small",
        r"\setlength{\tabcolsep}{5pt}",
        r"\begin{tabular}{@{}llrrl@{}}",
        r"\toprule",
        r"\textbf{Evaluated unit} & \textbf{Metric} & $n$ & \textbf{Score} & \textbf{vs.\ chance} \\",
        r"\midrule",
        r"\multicolumn{5}{@{}l@{}}{\textbf{TASK 1: Variable value inference.}\quad $(F_{ij},\,V)\;\mapsto\;\hat{v}_{ij}$} \\",
        r"\multicolumn{5}{@{}l@{}}{\footnotesize\itshape recovering $v_{ij}$ from the configuration alone suggests $F_{ij}$ faithfully realizes its variable values} \\",
        r"\addlinespace[2pt]",
        rf"\quad all variables $V$ & exact match & {int(numbers['task1_n_variables'])} & \textbf{{{task1_all:.3f}}} & {_ratio(task1_all, task1_random_all)} \\",
        rf"\quad hypothesized cause $X$ only & exact match & {int(numbers['task1_n_causal_variables'])} & \textbf{{{task1_causal:.3f}}} & {_ratio(task1_causal, task1_random_causal)} \\",
        r"\addlinespace[2pt]\midrule",
        r"\multicolumn{5}{@{}l@{}}{\textbf{TASK 2: Config-to-simulation mapping.}\quad $\{(F_{ij},\ S_{i\phi(j)})\}_{j=1}^{\mathrm{J}} \mapsto \hat{\phi}$} \\",
        r"\multicolumn{5}{@{}l@{}}{\footnotesize\itshape matching masked simulations to their configurations suggests the level $x_j$ is what separates them} \\",
        r"\addlinespace[2pt]",
        rf"\quad configuration--simulation pair & accuracy & {int(numbers['task2_n_pairs'])}  & \textbf{{{task2_item:.3f}}} & {_ratio(task2_item, task2_random_item)} \\",
        rf"\quad whole matched group $i$ (all $\mathrm{{J}}$ correct) & accuracy & {int(numbers['task2_n_groups'])} & \textbf{{{task2_group:.3f}}} & {_ratio(task2_group, task2_random_group)} \\",
        r"\addlinespace[2pt]\midrule",
        r"\multicolumn{5}{@{}l@{}}{\textbf{TASK 3: Within-group variable inference.}\quad $\{(F_{ij},\,S_{ij})\}_{j=1}^{\mathrm{J}}\;\mapsto\;\hat{X}$} \\",
        r"\multicolumn{5}{@{}l@{}}{\footnotesize\itshape inferring $\hat{X}\approx X$ suggests no other variable dominates the within-group difference} \\",
        r"\addlinespace[2pt]",
        rf"\quad matched group $i$ & human $(\hat{{X}},X)$ match & {int(numbers.get('task3_n_groups', numbers['task2_n_groups']))} & {task3_score_text} & -- \\",
        r"\bottomrule",
        r"\end{tabular}",
        r"\caption{\textbf{Fidelity estimation of the \texttt{AEROBAT}-generated environments.} \textbf{Chance} is computed from the actual answer space: for TASK 1 the expected exact-match rate of a guesser drawing uniformly from each variable's candidate values, and for TASK 2 that of a uniform random one-to-one map.}",
        r"\label{tab:fidelity}",
        r"\end{table*}",
        "",
    ]
    return "\n".join(lines)


def write_environment_fidelity_latex(numbers: Mapping[str, object], path: str | Path) -> Path:
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
