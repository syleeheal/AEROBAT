DEFAULT_PRIOR_SCALE = math.sqrt(2) / 2


def _effect_class_key(value: object) -> str:
    return str(value).strip().lower().replace(" ", "_")


def _closest_prior_scale(frame: pd.DataFrame, default_scale: float) -> float:
    scales = frame.prior_scale.dropna().drop_duplicates()
    if scales.empty:
        raise ValueError("Prior-sensitivity frame has no prior scales")
    return float(min(scales, key=lambda value: abs(float(value) - default_scale)))


def prior_sensitivity_table(
    frame: pd.DataFrame,
    *,
    default_scale: float = DEFAULT_PRIOR_SCALE,
) -> pd.DataFrame:
    """Return the Appendix E prior-sensitivity table data."""
    default = _closest_prior_scale(frame, default_scale)
    default_classes = (
        frame[frame.prior_scale == default][["behavior_name", "axis_slug", "effect_class"]]
        .rename(columns={"effect_class": "default_effect_class"})
        .drop_duplicates(["behavior_name", "axis_slug"])
    )
    scored = frame.merge(default_classes, on=["behavior_name", "axis_slug"], how="left")
    if scored.default_effect_class.isna().any():
        raise ValueError("Every hypothesis must have a default-prior classification")

    rows = []
    for scale, block in scored.groupby("prior_scale", sort=True):
        counts = block.effect_class.map(_effect_class_key).value_counts()
        rows.append(
            {
                "prior_scale": float(scale),
                "is_default": math.isclose(float(scale), default, rel_tol=1e-12, abs_tol=1e-12),
                "hypotheses": block[["behavior_name", "axis_slug"]].drop_duplicates().shape[0],
                "positive": int(counts.get("positive", 0)),
                "negative": int(counts.get("negative", 0)),
                "no_effect": int(counts.get("no_effect", 0)),
                "inconclusive": int(counts.get("inconclusive", 0)),
                "class_agreement": float(
                    block.effect_class.map(_effect_class_key).eq(
                        block.default_effect_class.map(_effect_class_key)
                    ).mean()
                ),
                "median_absolute_log10_shift": float(block.absolute_log10_shift.median()),
                "max_absolute_log10_shift": float(block.absolute_log10_shift.max()),
                "median_mcse": float(block.log10_bf10_mcse.median()),
                "max_mcse": float(block.log10_bf10_mcse.max()),
            }
        )
    return pd.DataFrame(rows)


def _prior_scale_label(scale: float, is_default: bool) -> str:
    if math.isclose(scale, DEFAULT_PRIOR_SCALE, rel_tol=1e-9, abs_tol=1e-9):
        suffix = r"^{\dagger}" if is_default else ""
        return rf"$\sqrt{{2}}/2 \approx {scale:.3f}{suffix}$"
    suffix = r"^{\dagger}" if is_default else ""
    return rf"${scale:.1f}{suffix}$"


