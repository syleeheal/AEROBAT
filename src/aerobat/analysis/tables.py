INTENSITY_RANK = {
    word: tier for tier, words in INTENSITY_TIERS.items() for word in words
}
EXAMPLE_MARKER_RE = re.compile(r"e\.g\.|such as|including|\(")


def _max_intensity(text: object) -> float:
    hits = [
        INTENSITY_RANK[word.lower()]
        for word in re.findall(r"[A-Za-z]+", str(text))
        if word.lower() in INTENSITY_RANK
    ]
    return float(max(hits)) if hits else math.nan


def _spearman(left: pd.Series, right: pd.Series) -> float:
    valid = pd.DataFrame({"left": left, "right": right}).dropna()
    if valid.left.nunique() < 2 or valid.right.nunique() < 2:
        return math.nan
    return float(valid.left.corr(valid.right, method="spearman"))


def rubric_semantics_table(criteria: pd.DataFrame, pairs: pd.DataFrame) -> pd.DataFrame:
    """Return the behavior-level semantic table used by the appendix."""
    anchors = criteria.copy()
    anchors["words"] = anchors.criterion_text.astype(str).str.split().str.len()
    anchors["examples_per_anchor"] = anchors.criterion_text.astype(str).str.count(
        EXAMPLE_MARKER_RE
    )
    anchors["intensity"] = anchors.criterion_text.map(_max_intensity)

    rows = []
    for behavior, block in anchors.groupby("target_behavior", sort=True):
        behavior_pairs = pairs[
            (pairs.target_behavior_left == behavior)
            & (pairs.target_behavior_right == behavior)
        ]
        distinct = behavior_pairs[
            (behavior_pairs.evidence_class_left != behavior_pairs.evidence_class_right)
            & (behavior_pairs.level_score_left == behavior_pairs.level_score_right)
        ]
        level_pairs = behavior_pairs[
            behavior_pairs.evidence_class_left == behavior_pairs.evidence_class_right
        ]
        ladder = []
        for _evidence_class, class_block in block.groupby("evidence_class"):
            ladder.append(
                _spearman(class_block.level_score, class_block.intensity)
            )
        rows.append(
            {
                "target_behavior": behavior,
                "words": float(block.words.mean()),
                "examples_per_anchor": float(block.examples_per_anchor.mean()),
                "distinctiveness": float(distinct.cosine_similarity.mean()),
                "level_gradient_rho": _spearman(
                    level_pairs.level_distance, level_pairs.cosine_similarity
                ),
                "intensity_rho": float(pd.Series(ladder).mean()),
            }
        )
    return pd.DataFrame(rows)


def _format_signed(value: object) -> str:
    if _is_missing(value):
        return "--"
    return f"{float(value):+.2f}"


