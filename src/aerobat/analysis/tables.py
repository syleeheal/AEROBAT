GENERALIZATION_CAPTION = (
    "Full statistical analytic result across subject agent models. Abbreviations: "
    "auth. = authority, comm. = communication, ctx. = context, info. = information, "
    r"instr. = instruction, rel. = relative, res. = resource; $\oslash$ = "
    r"inconclusive effect; $0$ = no effect."
)


def _generalization_result_rows(frame: pd.DataFrame) -> list[str]:
    lines = []
    previous_behavior = None
    previous_group = None
    behavior_lines: list[str] = []
    behavior_line_index = 0

    for row in frame.itertuples(index=False):
        behavior = row.behavior_name
        group = (row.behavior_name, row.variable)
        is_new_group = group != previous_group
        if behavior != previous_behavior:
            behavior_lines = _behavior_label_lines(behavior)
            behavior_line_index = 0

        behavior_cell = (
            behavior_lines[behavior_line_index]
            if behavior_line_index < len(behavior_lines)
            else ""
        )
        cause_cell = _compact_label(row.variable) if is_new_group else ""
        manipulated_cell = (
            _manipulated_component_label(row.manipulated_component)
            if is_new_group
            else ""
        )
        cells = [
            behavior_cell,
            cause_cell,
            manipulated_cell,
            _pretty_label(row.alpha),
            _format_int(row.n),
            _format_table_bf(row.bf10),
            _format_decimal(row.Delta),
            _format_decimal(row.tau),
            _format_p(row.p_tau),
            _effect_label(row.effect_class),
        ]
        lines.append(" & ".join(cells) + r" \\")

        previous_behavior = behavior
        previous_group = group
        behavior_line_index += 1
    return lines


