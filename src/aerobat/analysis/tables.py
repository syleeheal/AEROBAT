def latex_escape(value: object) -> str:
    text = str(value)
    replacements = {
        "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$",
        "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
        "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
    }
    for source, target in replacements.items():
        text = text.replace(source, target)
    return text


def format_bf(value: float) -> str:
    if not math.isfinite(value):
        return "--"
    if abs(value) >= 1_000:
        exponent = int(math.floor(math.log10(abs(value))))
        return rf"${value / 10 ** exponent:.2f}\times 10^{{{exponent}}}$"
    return f"{value:.3f}"


def results_latex(frame: pd.DataFrame) -> str:
    """Create the includeable table body used by the main/appendix result tables."""
    lines = [r"% generated by aerobat.analysis.tables", r"\begin{longtable}{llrrrrrrrrl}", r"\toprule", r"$Y$ & $X$ & $|D_h|$ & $B$ & $J$ & $T$ & $n$ & $\mathrm{BF}_{10}$ & $\Delta$ & $\tau$ & Class \\", r"\midrule"]
    symbols = {
        "Positive": "$+$",
        "Negative": "$-$",
        "No effect": "$0$",
        "Inconclusive": r"$\oslash$",
        "positive": "$+$",
        "negative": "$-$",
        "no_effect": "$0$",
        "inconclusive": r"$\oslash$",
        "direction_unresolved": r"$\oslash$",
    }
    for row in frame.itertuples(index=False):
        lines.append(
            f"{latex_escape(row.behavior_name)} & {latex_escape(row.variable)} & {int(row.D_h)} & {int(row.B)} & {int(row.J)} & {int(row.T)} & {int(row.n)} & {format_bf(float(row.bf10))} & {float(row.Delta):.3f} & {float(row.tau):.3f} & {symbols.get(row.effect_class, row.effect_class)} \\\\"
        )
    lines.extend([r"\bottomrule", r"\end{longtable}"])
    return "\n".join(lines) + "\n"


def write_results_latex(frame: pd.DataFrame, path: str | Path) -> Path:
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(results_latex(frame), encoding="utf-8")
    return target


